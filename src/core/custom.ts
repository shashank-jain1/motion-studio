/**
 * Custom components (escape hatch): src/engine/custom/<Name>.tsx + generated registry index.ts.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { CUSTOM_DIR } from "./paths";
import { invalidateBundle } from "./render";

const NAME_RE = /^[A-Z][A-Za-z0-9]{0,63}$/;
const RESERVED = new Set(["Index", "React", "Object", "Array", "Function", "String", "Number", "Boolean", "Symbol", "Map", "Set", "Promise", "Error", "Date", "Math", "JSON", "CUSTOM"]);

export const listCustomComponents = (): string[] => {
  if (!fs.existsSync(CUSTOM_DIR)) return [];
  return fs
    .readdirSync(CUSTOM_DIR)
    .filter((f) => f.endsWith(".tsx") && NAME_RE.test(f.slice(0, -4)))
    .map((f) => f.slice(0, -4))
    .sort();
};

/** Regenerate src/engine/custom/index.ts from the .tsx files present. */
export const regenerateCustomIndex = (): string => {
  fs.mkdirSync(CUSTOM_DIR, { recursive: true });
  const names = listCustomComponents();
  const lines = [
    "// AUTO-GENERATED by src/core/custom.ts (write_custom_component). Do not edit by hand.",
    'import type { FC } from "react";',
    ...names.map((n) => `import ${n} from "./${n}";`),
    "",
    `export const CUSTOM: Record<string, FC<any>> = {${names.length ? ` ${names.join(", ")} ` : ""}};`,
    "",
  ];
  const file = path.join(CUSTOM_DIR, "index.ts");
  const content = lines.join("\n");
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) fs.writeFileSync(file, content);
  return file;
};

type EsbuildLike = { transformSync: (code: string, opts: Record<string, unknown>) => unknown };
let esbuild: EsbuildLike | null | undefined;
const loadEsbuild = (): EsbuildLike | null => {
  if (esbuild !== undefined) return esbuild;
  esbuild = null;
  try {
    const req = createRequire(import.meta.url);
    const bundlerPkg = req.resolve("@remotion/bundler/package.json");
    esbuild = createRequire(bundlerPkg)("esbuild") as EsbuildLike;
  } catch {
    /* syntax check unavailable */
  }
  return esbuild;
};

/** Returns an error message if the TSX doesn't parse, else null. */
export const checkTsxSyntax = (code: string, filename = "Component.tsx"): string | null => {
  const eb = loadEsbuild();
  if (!eb) return null;
  try {
    eb.transformSync(code, { loader: "tsx", jsx: "automatic", sourcefile: filename, logLevel: "silent" });
    return null;
  } catch (e) {
    const err = e as { errors?: { text: string; location?: { line: number; column: number; lineText?: string } }[]; message?: string };
    if (err.errors?.length) {
      return err.errors
        .slice(0, 5)
        .map((x) => (x.location ? `${filename}:${x.location.line}:${x.location.column}: ${x.text}\n    ${x.location.lineText ?? ""}` : x.text))
        .join("\n");
    }
    return String(err.message ?? e);
  }
};

export type WriteCustomResult = { name: string; path: string; components: string[]; replaced: boolean };

/**
 * Write src/engine/custom/<Name>.tsx (must `export default` a React component receiving
 * { t, duration, width, height, ...props }), regenerate the registry and invalidate the bundle.
 * Throws with a readable message on invalid names or syntax errors (nothing is written then).
 */
export const writeCustomComponent = (name: string, code: string): WriteCustomResult => {
  if (!NAME_RE.test(name)) throw new Error(`Invalid component name "${name}": use PascalCase letters/digits, e.g. "OrbitingLogos"`);
  if (RESERVED.has(name)) throw new Error(`"${name}" is a reserved name; pick another`);
  if (!/export\s+default\b/.test(code)) throw new Error("The code must `export default` the component (a function receiving { t, duration, width, height, ...props }).");
  const syntax = checkTsxSyntax(code, `${name}.tsx`);
  if (syntax) throw new Error(`Syntax error, nothing was written:\n${syntax}`);
  fs.mkdirSync(CUSTOM_DIR, { recursive: true });
  const file = path.join(CUSTOM_DIR, `${name}.tsx`);
  const replaced = fs.existsSync(file);
  fs.writeFileSync(file, code.endsWith("\n") ? code : code + "\n");
  regenerateCustomIndex();
  invalidateBundle();
  return { name, path: file, components: listCustomComponents(), replaced };
};

export const readCustomComponent = (name: string): string => {
  if (!NAME_RE.test(name)) throw new Error(`Invalid component name "${name}"`);
  const file = path.join(CUSTOM_DIR, `${name}.tsx`);
  if (!fs.existsSync(file)) throw new Error(`Custom component "${name}" not found`);
  return fs.readFileSync(file, "utf8");
};

export const deleteCustomComponent = (name: string): void => {
  if (!NAME_RE.test(name)) throw new Error(`Invalid component name "${name}"`);
  fs.rmSync(path.join(CUSTOM_DIR, `${name}.tsx`), { force: true });
  regenerateCustomIndex();
  invalidateBundle();
};
